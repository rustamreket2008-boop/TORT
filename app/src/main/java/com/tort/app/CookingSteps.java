package com.tort.app;

public class CookingSteps {

    public static String get(String cake) {

        if (cake.contains("Шоколад")) {
            return "1. Тухм ва шакарро омехта кун.\n\n"
                + "2. Шир ва равғанро илова кун.\n\n"
                + "3. Орд ва какаоро илова кун.\n\n"
                + "4. Хамирро ба қолаб рез.\n\n"
                + "5. Дар танӯри 180°C тақрибан 30–35 дақиқа паз.\n\n"
                + "6. Пас аз хунук шудан бо крем оро деҳ.";
        }

        if (cake.contains("Асалӣ")) {
            return "1. Тухм, шакар ва асалро омехта кун.\n\n"
                + "2. Равған ва ордро илова кун.\n\n"
                + "3. Хамирро тайёр карда ба қабатҳо ҷудо кун.\n\n"
                + "4. Қабатҳоро дар танӯр паз.\n\n"
                + "5. Бо крем якҷо карда оро деҳ.";
        }

        return "1. Тухм ва шакарро омехта кун.\n\n"
            + "2. Шир ва равғанро илова кун.\n\n"
            + "3. Орд ва разрыхлительро илова кун.\n\n"
            + "4. Хамирро ба қолаб рез.\n\n"
            + "5. Дар танӯри 180°C то пухта шудан паз.\n\n"
            + "6. Хунук карда бо крем оро деҳ.";
    }
}
